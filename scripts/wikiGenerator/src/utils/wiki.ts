import { existsSync } from "fs";
import { readFile, writeFile } from "fs/promises";

import { TOP_AUTOGENERATED_HEADER, BOTTOM_AUTOGENERATED_HEADER } from "../constants/header.js";

export async function writeToDocsFile(filePath: string, content: string): Promise<void> {
    filePath = filePath + ".md";

    let fileContents: string[] = [];
    if (existsSync(filePath)) {
        fileContents = (await readFile(filePath, { encoding: "utf-8" })).split("\n");
    }

    let topAutogeneratedHeaderLine = fileContents.findIndex((line) =>
        line.startsWith(TOP_AUTOGENERATED_HEADER)
    );

    let bottomAutogeneratedHeaderLine = fileContents
        .slice(topAutogeneratedHeaderLine)
        .findIndex((line) => line.startsWith(BOTTOM_AUTOGENERATED_HEADER));

    if (topAutogeneratedHeaderLine === -1) {
        topAutogeneratedHeaderLine = 0;
        bottomAutogeneratedHeaderLine = 0;
    }

    const fileData = [
        ...fileContents.slice(0, topAutogeneratedHeaderLine),
        TOP_AUTOGENERATED_HEADER,
        "",
        content,
        "",
        BOTTOM_AUTOGENERATED_HEADER,
        ...fileContents.slice(bottomAutogeneratedHeaderLine + 1, fileContents.length),
    ];

    writeFile(filePath, fileData.join("\n"));
}
